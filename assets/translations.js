(function () {
  const LS_KEY = 'nk_lang';
  const SUPPORTED = ['en', 'ru', 'ua', 'de', 'cz'];

  function getLang() {
    const saved = localStorage.getItem(LS_KEY);
    if (saved && SUPPORTED.includes(saved)) return saved;
    const nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
    if (nav === 'uk') return 'ua';
    if (nav === 'cs') return 'cz';
    return SUPPORTED.includes(nav) ? nav : 'en';
  }

  function applyTranslations(lang) {
    const dict = I18N[lang] || I18N.en;
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.dataset.i18n;
      const txt = dict[key];
      if (txt === undefined) return;
      // Allow <em> tags for italic emphasis (safe: hardcoded dictionary)
      if (txt.indexOf('<') >= 0) el.innerHTML = txt;
      else el.textContent = txt;
    });
    // Translate input/textarea placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.dataset.i18nPlaceholder;
      const txt = dict[key];
      if (txt !== undefined) el.setAttribute('placeholder', txt);
    });
    document.querySelectorAll('[data-lang]').forEach((el) => {
      el.classList.toggle('active', el.dataset.lang === lang);
    });
    const label = document.querySelector('.lang-current span');
    if (label) label.textContent = lang.toUpperCase();
    // why-dubai page has its own label
    const wdLabel = document.getElementById('wd-lang-label');
    if (wdLabel) wdLabel.textContent = lang.toUpperCase();
    document.documentElement.lang = lang === 'ua' ? 'uk' : (lang === 'cz' ? 'cs' : lang);
  }

  applyTranslations(getLang());

  document.addEventListener('click', (e) => {
    const link = e.target.closest('[data-lang]');
    if (!link) return;
    e.preventDefault();
    const lang = link.dataset.lang;
    if (!SUPPORTED.includes(lang)) return;
    localStorage.setItem(LS_KEY, lang);
    applyTranslations(lang);
    document.querySelector('.lang-switch')?.classList.remove('open');
  });
})();
